// Aggregate ACTUAL household trip legs from a run. Household means plan
// member ids (plus run agents flagged household:true); anything else is
// background and excluded. Legs are legs, never visits; nothing is
// extrapolated and no variance is fabricated.
export function summarizePlanRun(run, plan) {
  // Summarises a production engine run: run.meta.days is the declared
  // period, run.trips holds walk-leg records (trip.agent is the engine key
  // such as "h1"), run.unavailable holds actual missing-data records, and
  // run.daily holds per-day engine summaries keyed by the same agent key.
  //
  // Units, kept separate on purpose: trip.minutes is one walk leg only —
  // rail/ride/wait minutes live in the daily commute_* fields or the
  // scenario, so travel_minutes is NOT whole-commute or all-travel time.
  // commute_minutes sums the daily commute_walk + commute_ride +
  // commute_wait fields (door-to-door only if those engine fields meet
  // the definition; the walk part is not double counted because the
  // all-purpose walk_minutes field is never added). Counts use actual
  // recorded legs only and are never extrapolated; no claim is made that
  // a longer window is better than the first 7 days.
  if (!isObj(run)) fail("run must be an object");
  if (!isObj(plan) || !Array.isArray(plan.members)) fail("plan must carry members");
  const planIds = plan.members.map((m) => m && m.id).filter((id) => typeof id === "string");
  // Canonical member map: production trip.agent holds the engine key
  // ("h1") while plan ids hold the scenario member id ("m1"); run.agents
  // links key -> id. Only household:true agents whose id matches a plan
  // id are included, so background agents (even one whose key looks like
  // a household key) never count. Legacy fixtures that carry only plan
  // ids (agent entries with just {id}, or no usable agent links at all)
  // resolve each plan id to itself.
  const keyToMember = new Map();
  const excluded = new Set();
  if (Array.isArray(run.agents)) {
    for (const a of run.agents) {
      if (!isObj(a)) continue;
      const key = typeof a.key === "string" ? a.key : (typeof a.id === "string" ? a.id : null);
      const id = typeof a.id === "string" ? a.id : null;
      if (key === null) continue;
      if (a.household === false) {
        excluded.add(key);
        if (id !== null) excluded.add(id);
        continue;
      }
      if (a.household === true && id !== null && planIds.includes(id)) {
        keyToMember.set(key, id);
        keyToMember.set(id, id);
      } else if (a.household === true && planIds.includes(key)) {
        keyToMember.set(key, key); // legacy: the agent id already is the plan id
      }
    }
    for (const k of excluded) keyToMember.delete(k);
  }
  const legacyCompat = keyToMember.size === 0; // no usable agent links: accept bare plan ids
  const resolveMember = (raw) => {
    if (typeof raw !== "string") return null;
    if (excluded.has(raw)) return null;
    if (keyToMember.has(raw)) return keyToMember.get(raw);
    if (legacyCompat && planIds.includes(raw)) return raw;
    return null; // background, unknown, or non-household agents excluded
  };
  const metaDays = run.meta && Number.isInteger(run.meta.days) && run.meta.days >= 0 ? run.meta.days : null;
  const totalDays = metaDays !== null
    ? metaDays
    : (Number.isInteger(run.total_days) && run.total_days >= 0 ? run.total_days : null);
  const inPeriod = (day) => Number.isInteger(day) && day >= 0 && (totalDays === null || day < totalDays);
  const tripList = Array.isArray(run.trips) ? run.trips : null;
  const dailyList = Array.isArray(run.daily) ? run.daily : null;
  if (!tripList && !dailyList) fail("run needs trips[] or daily[]");
  // Day coverage comes from daily summaries (bounded to the declared
  // period), never from trip days: a full-remote or all-home stretch with
  // no trips still counts every day the engine summarised.
  const coveredDays = new Set();
  let householdDailySummaries = 0;
  const commuteFull = new Map();
  const commuteFirst = new Map();
  const addCommute = (map, member, s) => {
    let entry = map.get(member);
    if (!entry) { entry = { minutes: 0, partial: false }; map.set(member, entry); }
    for (const v of [s.commute_walk_minutes, s.commute_ride_minutes, s.commute_wait_minutes]) {
      if (typeof v === "number" && Number.isFinite(v)) entry.minutes += v;
      else entry.partial = true; // a required source is unknown: label it, never invent it
    }
  };
  if (dailyList) {
    for (const entry of dailyList) {
      if (!isObj(entry) || !Array.isArray(entry.days)) continue;
      const member = resolveMember(entry.agent);
      if (member === null) continue;
      for (const s of entry.days) {
        if (!isObj(s) || !inPeriod(s.day)) continue; // out-of-period and invalid days never count
        householdDailySummaries += 1;
        coveredDays.add(s.day);
        addCommute(commuteFull, member, s);
        if (s.day < 7) addCommute(commuteFirst, member, s);
      }
    }
  }
  const legs = [];
  const tripIds = [];
  if (tripList) {
    for (const t of tripList) {
      if (!isObj(t)) continue;
      const member = resolveMember(t.agent ?? t.member ?? t.member_id ?? t.agent_id);
      if (member === null) continue;
      const day = Number.isInteger(t.day) ? t.day : 0; // legacy trips may omit day
      if (!inPeriod(day)) continue; // outside the declared period or invalid
      const purpose = typeof t.purpose === "string" && t.purpose.length > 0 ? t.purpose : "other";
      const rawMin = t.minutes ?? t.travel_minutes ?? t.duration_min;
      // Negative/NaN/missing minutes are counted as missing; finite known
      // leg minutes are summed and the total is labelled partial.
      const minutes = typeof rawMin === "number" && Number.isFinite(rawMin) && rawMin >= 0 ? rawMin : null;
      if (typeof t.id === "string") tripIds.push(t.id);
      legs.push({ day, member, purpose, minutes });
    }
  }
  const blank = () => ({
    trips: 0, travel_minutes: 0, travel_minutes_partial: false,
    commute_minutes: null, commute_minutes_partial: householdDailySummaries === 0,
    by_member: {}, by_purpose: {},
  });
  const sub = () => ({ trips: 0, travel_minutes: 0, travel_minutes_partial: false });
  const add = (acc, leg) => {
    acc.trips += 1;
    if (leg.minutes !== null) acc.travel_minutes += leg.minutes;
    else acc.travel_minutes_partial = true;
    const m = (acc.by_member[leg.member] = acc.by_member[leg.member] || sub());
    m.trips += 1;
    if (leg.minutes !== null) m.travel_minutes += leg.minutes;
    else m.travel_minutes_partial = true;
    const p = (acc.by_purpose[leg.purpose] = acc.by_purpose[leg.purpose] || sub());
    p.trips += 1;
    if (leg.minutes !== null) p.travel_minutes += leg.minutes;
    else p.travel_minutes_partial = true;
  };
  const first = blank();
  const full = blank();
  const activeTripDays = new Set();
  let legsMissingMinutes = 0;
  for (const leg of legs) {
    add(full, leg);
    if (leg.day < 7) add(first, leg);
    activeTripDays.add(leg.day);
    if (leg.minutes === null) legsMissingMinutes += 1;
  }
  const attachCommute = (acc, map) => {
    let total = 0;
    let partial = householdDailySummaries === 0;
    for (const [member, c] of map) {
      total += c.minutes;
      if (c.partial) partial = true;
      if (acc.by_member[member]) {
        acc.by_member[member].commute_minutes = c.minutes;
        acc.by_member[member].commute_minutes_partial = c.partial;
      }
    }
    if (householdDailySummaries > 0) {
      acc.commute_minutes = total;
      acc.commute_minutes_partial = partial;
    }
  };
  attachCommute(full, commuteFull);
  attachCommute(first, commuteFirst);
  // Unavailable days are actual missing-data records only: a quiet day
  // with no trips and no record is not missing.
  const unavailableDays = new Set();
  let unavailableRecords = 0;
  if (Array.isArray(run.unavailable)) {
    for (const u of run.unavailable) {
      if (!isObj(u)) continue;
      if (resolveMember(u.agent) === null) continue;
      if (!inPeriod(u.day)) continue;
      unavailableRecords += 1;
      unavailableDays.add(u.day);
    }
  }
  const seenMembers = new Set(legs.map((l) => l.member));
  const observedDays = householdDailySummaries > 0 ? coveredDays : activeTripDays;
  return {
    first_7_days: first,
    full_period: full,
    day_coverage: {
      observed_days: observedDays.size,
      active_trip_days: activeTripDays.size,
      total_days: totalDays === null ? 0 : totalDays,
      coverage_source: householdDailySummaries > 0 ? "daily" : "trips_only",
    },
    missing: {
      members_without_trips: planIds.filter((id) => !seenMembers.has(id)).sort(),
      unavailable_records: unavailableRecords,
      unavailable_days: unavailableDays.size,
      legs_missing_minutes: legsMissingMinutes,
    },
    evidence: { trip_ids: tripIds.slice(0, 200), trip_ids_truncated: tripIds.length > 200 },
  };
}
