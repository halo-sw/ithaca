// Household routine plan core (pure, browser-safe).
//
// A life plan adjusts ONLY whitelisted per-member routine fields of an
// engine scenario. It never invents workplaces, routes, minutes, costs,
// schools, diagnoses, or residents: anything the model cannot ground goes
// to `questions` (blocks confirmation) or `unmodeled` (stays visible).
//
// Pipeline: buildLifePlanInput -> (model) -> validateLifePlan ->
// confirmLifePlan -> applyLifePlan. Explanations (lifePlanExplanation)
// and run summaries (summarizePlanRun) are generated by code, never by
// the model, so rationale stays measurable.

export const WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];

export const CHANGE_FIELDS = [
  "preferences",
  "workdays",
  "schooldays",
  "errands_per_week",
  "park_walks_per_week",
  "clinic_visits_per_month",
  "cafe_visits_per_week",
  "vet_visits_per_month",
  "home_office",
  "home_office_days",
  "dog_walk_morning",
  "commute",
  "school",
];

export const OBSERVATION_CODES = [
  "commute",
  "school",
  "errands",
  "walks",
  "remote_days",
  "clinic",
  "pet_care",
  "monthly_cost",
  "daily_variation",
];

export const MAX_MEMBERS = 8;
export const MAX_CHANGES_PER_MEMBER = 15;
export const MAX_OBSERVATIONS = 8;
export const MAX_QUESTIONS = 8;
export const MAX_UNMODELED = 8;
export const MAX_REVIEW = 8;
export const MAX_PREFERENCES_CHARS = 500;
export const MAX_TEXT_ITEM_CHARS = 300;
export const MAX_EVIDENCE_CHARS = 2000;
export const MAX_USER_MESSAGES = 12;
export const MAX_USER_TEXT_CHARS = 12000;
export const MAX_PLAN_CONTEXT_CHARS = 1200;

export const LEGACY_SCHOOL_PROXY_NOTICE =
  "School routes are nearby POI proxies, not assigned or enrolled schools.";

const INT_RANGES = {
  park_walks_per_week: [0, 7],
  clinic_visits_per_month: [0, 31],
  cafe_visits_per_week: [0, 5],
  vet_visits_per_month: [0, 4],
};

const ERRAND_KEYS = ["supermarket", "convenience"];

function fail(msg) {
  throw new Error(`life-plan: ${msg}`);
}

function isObj(v) {
  return v !== null && typeof v === "object" && !Array.isArray(v);
}

function clone(v) {
  return v === undefined ? undefined : JSON.parse(JSON.stringify(v));
}

function str(v, max) {
  const s = typeof v === "string" ? v : "";
  return s.length > max ? s.slice(0, max) : s;
}

// Deterministic key-sorted stringify for stable signatures.
export function stableStringify(v) {
  if (v === null || v === undefined) return "null";
  if (Array.isArray(v)) return `[${v.map(stableStringify).join(",")}]`;
  if (isObj(v)) {
    return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${stableStringify(v[k])}`).join(",")}}`;
  }
  return JSON.stringify(v);
}

// FNV-1a 32-bit hex (deterministic, non-secret; stale-plan detection only).
export function signatureHash(text) {
  let h = 0x811c9dc5;
  const s = String(text);
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return `lp1-${(h >>> 0).toString(16).padStart(8, "0")}`;
}

function userSourced(source) {
  const s = String(source || "").toLowerCase();
  return s.includes("user") || s.includes("customer") || s.includes("stated") || s.includes("customer-input");
}

// Real customer profiles nest per-member fields in an array:
// profile.members = { value: [{ role, label, preferences?, workdays?, ... }],
//   source: "customer"|"default", note }. Scenario member order/id
// (m1, m2, ...) maps to the array index; only fields actually present on
// the entry count, never computed base routine defaults. A per-field
// {value,source} object keeps its exact provenance when present;
// otherwise the bare value inherits the array-level source.
// The legacy flat shape ({ h1: { workdays: { value, source } } }) still reads.
function memberArrayIndex(memberId, order) {
  const m = /^m(\d+)$/.exec(String(memberId || ""));
  if (m) return Number(m[1]) - 1;
  return order;
}

function profileField(profile, memberId, field, order = 0) {
  const mv = profile && profile.members && profile.members.value;
  if (Array.isArray(mv)) {
    const entry = mv[memberArrayIndex(memberId, order)];
    if (isObj(entry) && Object.prototype.hasOwnProperty.call(entry, field)) {
      const v = entry[field];
      if (isObj(v) && "value" in v) {
        return { found: true, value: v.value, source: v.source, user: userSourced(v.source) };
      }
      return { found: true, value: v, source: profile.members.source, user: userSourced(profile.members.source) };
    }
    return { found: false, value: undefined, source: undefined, user: false };
  }
  const scopes = [profile && profile.members && profile.members[memberId], profile && profile[memberId]];
  for (const scope of scopes) {
    if (isObj(scope) && field in scope) {
      const entry = scope[field];
      if (isObj(entry) && "value" in entry) {
        return { found: true, value: entry.value, source: entry.source, user: userSourced(entry.source) };
      }
      return { found: false, value: undefined, source: undefined, user: false };
    }
  }
  return { found: false, value: undefined, source: undefined, user: false };
}

function boundedStr(v, max) {
  const s = typeof v === "string" ? v : "";
  return s.length > max ? s.slice(0, max) : s;
}

// Known workplaces, officeDays and pets travel as stated context with
// source, bounded — the model may reference them, never invent beyond.
function buildProfileContext(profile) {
  const ctx = { officeDays: null, pets: null, workplaces: [] };
  for (const key of ["officeDays", "pets"]) {
    const e = profile ? profile[key] : null;
    if (isObj(e) && "value" in e) {
      ctx[key] = { value: clone(e.value), source: String(e.source || "") };
    }
  }
  const wv = profile ? profile.workplaces : null;
  const list = Array.isArray(wv) ? wv : (isObj(wv) && Array.isArray(wv.value) ? wv.value : []);
  const wsource = String((isObj(wv) && wv.source) || "");
  for (const w of list.slice(0, MAX_MEMBERS)) {
    if (!isObj(w)) continue;
    ctx.workplaces.push({
      member: Number.isInteger(w.member) ? w.member : null,
      station: boundedStr(w.resolved && w.resolved.station, 200),
      place: boundedStr(w.resolved && w.resolved.place && w.resolved.place.name, 200),
      noCommute: w.noCommute === true,
      source: wsource,
    });
  }
  return ctx;
}

function scenarioMembers(scenario) {
  const m = scenario && scenario.household && scenario.household.members;
  if (!Array.isArray(m)) fail("scenario needs household.members array");
  return m;
}

function pickHomes(scenario) {
  if (Array.isArray(scenario.homes)) return clone(scenario.homes);
  if (Array.isArray(scenario.selected_homes)) return clone(scenario.selected_homes);
  if (Array.isArray(scenario.candidates)) return clone(scenario.candidates);
  return null;
}

// Build the bounded plain-data input the model sees. Scenario routine
// values are recorded as ASSUMPTIONS (never stated facts); only exact
// user-sourced profile member values count as stated.
export function buildLifePlanInput({ scenario, profile = {}, messages = [], lang = "en" } = {}) {
  if (!isObj(scenario)) fail("scenario must be an object");
  const raw = scenarioMembers(scenario);
  if (raw.length === 0) fail("scenario needs at least one household member");
  if (raw.length > MAX_MEMBERS) fail(`at most ${MAX_MEMBERS} members (got ${raw.length})`);
  const seen = new Set();
  const members = raw.map((m, i) => {
    if (!isObj(m) || typeof m.id !== "string" || m.id.length === 0) fail(`member index ${i} needs a string id`);
    if (seen.has(m.id)) fail(`duplicate member id ${JSON.stringify(m.id)}`);
    seen.add(m.id);
    const assumptions = {};
    for (const f of CHANGE_FIELDS) {
      if (m[f] !== undefined) assumptions[f] = clone(m[f]);
    }
    return {
      id: m.id,
      label: str(m.label, 200),
      role: str(m.role, 100),
      work: m.work === undefined ? null : clone(m.work),
      work_unresolved: m.work_unresolved === true,
      workdays: Array.isArray(m.workdays) ? [...m.workdays] : null,
      home_office_days: Array.isArray(m.home_office_days) ? [...m.home_office_days] : null,
      schooldays: Array.isArray(m.schooldays) ? [...m.schooldays] : null,
      school: m.school === undefined ? null : clone(m.school),
      assumptions,
    };
  });
  const userTexts = (Array.isArray(messages) ? messages : [])
    .filter((m) => isObj(m) && m.role === "user" && typeof m.content === "string" && m.content.length > 0)
    .slice(-MAX_USER_MESSAGES)
    .map((m) => m.content);
  // Bound total evidence chars: keep the last 12 user messages, trimming
  // the oldest message's front when the total exceeds the cap.
  const texts = [...userTexts];
  let total = texts.reduce((n, t) => n + t.length, 0);
  while (texts.length > 0 && total > MAX_USER_TEXT_CHARS) {
    const over = total - MAX_USER_TEXT_CHARS;
    if (texts[0].length > over) {
      texts[0] = texts[0].slice(over);
      total = MAX_USER_TEXT_CHARS;
    } else {
      total -= texts[0].length;
      texts.shift();
    }
  }
  const profile_values = {};
  const profile_sources = {};
  const stated_fields = {};
  members.forEach((m, i) => {
    for (const f of CHANGE_FIELDS) {
      const hit = profileField(profile, m.id, f, i);
      if (hit.found) {
        (profile_values[m.id] = profile_values[m.id] || {})[f] = clone(hit.value);
        (profile_sources[m.id] = profile_sources[m.id] || {})[f] = String(hit.source || "");
        if (hit.user) (stated_fields[m.id] = stated_fields[m.id] || []).push(f);
      }
    }
  });
  const legacy_nearest_school =
    scenario.nearest_school === true || scenario.nearestSchool === true ||
    members.some((m) => m.school === true);
  const homes = pickHomes(scenario);
  const start_date = typeof scenario.start_date === "string" ? scenario.start_date : null;
  const days = Number.isInteger(scenario.days) ? scenario.days : null;
  const seed = scenario.seed === undefined ? null : clone(scenario.seed);
  // Altered execution conditions invalidate approval: the signature covers
  // the profile sources (not just values), the seed, criteria overrides,
  // and the work/school day lengths alongside the household evidence.
  const criteria_overrides = scenario.criteria_overrides === undefined ? null : clone(scenario.criteria_overrides);
  const workday_minutes = scenario.workday_minutes === undefined ? null : clone(scenario.workday_minutes);
  const schoolday_minutes = scenario.schoolday_minutes === undefined ? null : clone(scenario.schoolday_minutes);
  const profile_context = buildProfileContext(profile);
  const core = {
    members, profile_values, profile_sources, profile_context, homes,
    start_date, days, lang, seed, criteria_overrides, workday_minutes,
    schoolday_minutes, user_texts: texts,
  };
  const input_signature = signatureHash(stableStringify(core));
  return { ...core, profile_sources, stated_fields, legacy_nearest_school, input_signature };
}

function sameProfileValue(evidence, value) {
  if (typeof value === "string") return evidence === value;
  if (typeof value === "number" || typeof value === "boolean") return evidence === String(value);
  return evidence === stableStringify(value);
}

function checkWeekdayList(value, field, memberId) {
  if (!Array.isArray(value) || value.length === 0) fail(`${memberId}.${field} needs a non-empty weekday list`);
  const seen = new Set();
  for (const w of value) {
    if (!WEEKDAYS.includes(w)) fail(`${memberId}.${field} has unknown weekday ${JSON.stringify(w)}`);
    if (seen.has(w)) fail(`${memberId}.${field} repeats weekday ${JSON.stringify(w)}`);
    seen.add(w);
  }
  return [...value];
}

function checkInt(value, field, memberId, lo, hi) {
  if (!Number.isInteger(value) || value < lo || value > hi) {
    fail(`${memberId}.${field} must be an integer ${lo}..${hi}`);
  }
  return value;
}

function checkCommuteRef(targetId, memberId, input) {
  if (targetId === memberId) fail(`${memberId}.commute cannot reference itself`);
  const target = (input.members || []).find((m) => m && m.id === targetId);
  if (!target) fail(`${memberId}.commute references unknown member ${JSON.stringify(targetId)}`);
  // Resolve against the ORIGINAL input work only — never another patch —
  // and reject cycles to patched or unresolved values the same way.
  const w = target.work;
  if (!isObj(w) || typeof w.type !== "string" || w.type === "none") {
    fail(`${memberId}.commute cannot copy ${targetId}: no resolved non-none work`);
  }
  if (target.work_unresolved === true) {
    fail(`${memberId}.commute cannot copy ${targetId}: work is unresolved`);
  }
  return `member:${targetId}`;
}

function checkSchoolValue(value, memberId) {
  if (value === false) return false;
  if (value === true) return true; // legacy: old recordings keep old behavior; apply records the proxy warning
  if (isObj(value)) {
    const keys = Object.keys(value).sort();
    if (keys.length !== 2 || keys[0] !== "level" || keys[1] !== "mode") {
      fail(`${memberId}.school allows only {mode, level}`);
    }
    if (value.mode !== "unresolved" && value.mode !== "nearby") {
      fail(`${memberId}.school mode must be "unresolved" or "nearby"`);
    }
    if (!["elementary", "middle", "high", "unknown"].includes(value.level)) {
      fail(`${memberId}.school level must be elementary, middle, high, or unknown`);
    }
    if (value.mode === "nearby" && value.level === "unknown") {
      fail(`${memberId}.school nearby needs a known level, never unknown`);
    }
    return { mode: value.mode, level: value.level };
  }
  fail(`${memberId}.school must be false, legacy true, or {mode, level}`);
  return false;
}

function checkFieldValue(field, value, memberId, input) {
  switch (field) {
    case "preferences":
      if (typeof value !== "string" || value.length === 0) fail(`${memberId}.preferences must be a non-empty string`);
      if (value.length > MAX_PREFERENCES_CHARS) fail(`${memberId}.preferences exceeds ${MAX_PREFERENCES_CHARS} chars`);
      return value;
    case "workdays":
    case "schooldays":
      return checkWeekdayList(value, field, memberId);
    case "home_office_days": {
      if (!Array.isArray(value)) fail(`${memberId}.home_office_days must be an array of weekday codes`);
      const seen = new Set();
      for (const w of value) {
        if (!WEEKDAYS.includes(w)) fail(`${memberId}.home_office_days has unknown weekday ${JSON.stringify(w)}`);
        if (seen.has(w)) fail(`${memberId}.home_office_days repeats weekday ${JSON.stringify(w)}`);
        seen.add(w);
      }
      return [...value];
    }
    case "errands_per_week": {
      if (!isObj(value)) fail(`${memberId}.errands_per_week must be an object`);
      const keys = Object.keys(value).sort();
      if (keys.length !== ERRAND_KEYS.length || !ERRAND_KEYS.every((k) => keys.includes(k))) {
        fail(`${memberId}.errands_per_week needs exactly {supermarket, convenience}`);
      }
      return {
        supermarket: checkInt(value.supermarket, "errands_per_week.supermarket", memberId, 0, 7),
        convenience: checkInt(value.convenience, "errands_per_week.convenience", memberId, 0, 7),
      };
    }
    case "commute":
      if (value === "none") return "none";
      if (typeof value === "string") {
        const ref = /^member:([A-Za-z0-9_-]+)$/.exec(value);
        if (ref) return checkCommuteRef(ref[1], memberId, input);
      }
      fail(`${memberId}.commute supports only "none" or "member:<id>" (no invented destinations, routes, minutes or costs)`);
      return "none";
    case "school":
      return checkSchoolValue(value, memberId);
    case "home_office":
    case "dog_walk_morning":
      if (typeof value !== "boolean") fail(`${memberId}.${field} must be boolean`);
      return value;
    default: {
      const range = INT_RANGES[field];
      if (!range) fail(`unsupported field ${JSON.stringify(field)} (never silently dropped)`);
      return checkInt(value, field, memberId, range[0], range[1]);
    }
  }
}

function checkEvidence(change, memberId, input) {
  const { field, basis, evidence } = change;
  if (basis !== "stated" && basis !== "proposal") fail(`${memberId}.${field} basis must be "stated" or "proposal"`);
  if (typeof evidence !== "string") fail(`${memberId}.${field} evidence must be a string`);
  if (evidence.length > MAX_EVIDENCE_CHARS) fail(`${memberId}.${field} evidence exceeds ${MAX_EVIDENCE_CHARS} chars`);
  if (basis === "proposal") return evidence;
  // basis "stated": exact-substring user text, or (non-preference fields
  // only) the exact explicit user-sourced profile value. Quoting is
  // traceability, not proof: the user still reviews before execution.
  if (evidence.length === 0) fail(`${memberId}.${field} stated needs non-empty evidence`);
  const inUserText = (input.user_texts || []).some((t) => typeof t === "string" && evidence.length > 0 && t.includes(evidence));
  if (inUserText) return evidence;
  if (field === "preferences") {
    fail(`${memberId}.preferences stated evidence must be user text, never demographic inference`);
  }
  // profile_values stores bare values (not {value,source} objects), so
  // compare directly with a user-sourced check from profile_sources.
  const pv = input.profile_values && input.profile_values[memberId];
  const src = input.profile_sources && input.profile_sources[memberId] && input.profile_sources[memberId][field];
  if (pv && Object.prototype.hasOwnProperty.call(pv, field) && userSourced(src) && sameProfileValue(evidence, pv[field])) {
    return evidence;
  }
  fail(`${memberId}.${field} stated evidence is not an exact user quote or matching user-sourced profile value`);
  return evidence;
}

function checkTextList(list, name, max) {
  if (!Array.isArray(list)) fail(`${name} must be an array`);
  if (list.length > max) fail(`${name} allows at most ${max} items (got ${list.length})`);
  return list.map((t, i) => {
    if (typeof t !== "string" || t.length === 0) fail(`${name}[${i}] must be a non-empty string`);
    if (t.length > MAX_TEXT_ITEM_CHARS) fail(`${name}[${i}] exceeds ${MAX_TEXT_ITEM_CHARS} chars`);
    return t;
  });
}

// Validate a raw model plan against the input it was built from. Returns a
// normalized plan; throws a concise error on anything unsupported, forged,
// out of range, or mismatched. Never silently drops unsafe fields.
export function validateLifePlan(raw, input) {
  if (!isObj(raw)) fail("plan must be an object");
  if (!isObj(input) || typeof input.input_signature !== "string") fail("input must carry input_signature");
  const topKeys = Object.keys(raw).sort();
  const allowedTop = ["members", "observations", "questions", "unmodeled", "review"].sort();
  for (const k of topKeys) {
    if (!allowedTop.includes(k)) fail(`unsupported top-level field ${JSON.stringify(k)}`);
  }
  for (const k of ["members", "observations", "questions", "unmodeled"]) {
    if (!(k in raw)) fail(`plan is missing ${JSON.stringify(k)}`);
  }
  const inputIds = (input.members || []).map((m) => m.id);
  if (!Array.isArray(raw.members) || raw.members.length !== inputIds.length) {
    fail(`plan must cover every input member exactly once (${inputIds.length} expected)`);
  }
  const seen = new Set();
  const members = raw.members.map((entry, i) => {
    if (!isObj(entry)) fail(`members[${i}] must be an object`);
    const ekeys = Object.keys(entry).sort();
    if (ekeys.length !== 2 || ekeys[0] !== "changes" || ekeys[1] !== "id") {
      fail(`members[${i}] allows only {id, changes}`);
    }
    if (typeof entry.id !== "string" || !inputIds.includes(entry.id)) {
      fail(`members[${i}] has unknown member id ${JSON.stringify(entry.id)}`);
    }
    if (seen.has(entry.id)) fail(`duplicate member id ${JSON.stringify(entry.id)}`);
    seen.add(entry.id);
    if (!Array.isArray(entry.changes)) fail(`${entry.id}.changes must be an array`);
    if (entry.changes.length > MAX_CHANGES_PER_MEMBER) {
      fail(`${entry.id} allows at most ${MAX_CHANGES_PER_MEMBER} changes`);
    }
    const changes = entry.changes.map((c, j) => {
      if (!isObj(c)) fail(`${entry.id}.changes[${j}] must be an object`);
      const ckeys = Object.keys(c).sort();
      const want = ["basis", "evidence", "field", "value"].sort();
      if (ckeys.length !== want.length || !ckeys.every((k, n) => k === want[n])) {
        fail(`${entry.id}.changes[${j}] allows only {field, value, basis, evidence}`);
      }
      if (!CHANGE_FIELDS.includes(c.field)) fail(`${entry.id} has unsupported field ${JSON.stringify(c.field)}`);
      const value = checkFieldValue(c.field, c.value, entry.id, input);
      const evidence = checkEvidence({ field: c.field, basis: c.basis, evidence: c.evidence }, entry.id, input);
      if (c.basis !== "stated" && c.basis !== "proposal") fail(`${entry.id}.${c.field} basis must be "stated" or "proposal"`);
      return { field: c.field, value: clone(value), basis: c.basis, evidence };
    });
    {
      const seenFields = new Set();
      for (const c of changes) {
        if (seenFields.has(c.field)) fail(`${entry.id} repeats field ${JSON.stringify(c.field)}`);
        seenFields.add(c.field);
      }
    }
    // Hybrid subset rule: home_office_days must be a subset of the
    // effective workdays (changes win, else the input member). Existing
    // remote sets are re-checked when the plan changes workdays — never
    // silently repaired.
    {
      const src = (input.members || []).find((m) => m && m.id === entry.id) || {};
      const workChange = changes.find((c) => c.field === "workdays");
      const remoteChange = changes.find((c) => c.field === "home_office_days");
      const effWork = workChange ? workChange.value
        : Array.isArray(src.workdays) ? src.workdays : null;
      let effRemote = null;
      let hasRemote = false;
      if (remoteChange) { effRemote = remoteChange.value; hasRemote = true; }
      else if (Array.isArray(src.home_office_days)) { effRemote = src.home_office_days; hasRemote = true; }
      else if (src.assumptions && Array.isArray(src.assumptions.home_office_days)) { effRemote = src.assumptions.home_office_days; hasRemote = true; }
      if (hasRemote) {
        if (!Array.isArray(effRemote)) fail(`${entry.id}.home_office_days must be an array`);
        const seenR = new Set();
        for (const w of effRemote) {
          if (!WEEKDAYS.includes(w)) fail(`${entry.id}.home_office_days has unknown weekday ${JSON.stringify(w)}`);
          if (seenR.has(w)) fail(`${entry.id}.home_office_days repeats weekday ${JSON.stringify(w)}`);
          seenR.add(w);
        }
        if (effRemote.length > 0) {
          if (!Array.isArray(effWork)) fail(`${entry.id}.home_office_days needs workdays to subset (got none)`);
          for (const w of effRemote) {
            if (!effWork.includes(w)) fail(`${entry.id}.home_office_days ${JSON.stringify(w)} is not in workdays`);
          }
        }
      }
    }
    return { id: entry.id, changes };
  });
  if (!Array.isArray(raw.observations)) fail("observations must be an array");
  if (raw.observations.length > MAX_OBSERVATIONS) fail(`at most ${MAX_OBSERVATIONS} observations`);
  const observations = raw.observations.map((o, i) => {
    if (!isObj(o)) fail(`observations[${i}] must be an object`);
    const okeys = Object.keys(o).sort();
    if (okeys.length !== 3 || okeys[0] !== "code" || okeys[1] !== "member_ids" || okeys[2] !== "reason") {
      fail(`observations[${i}] allows only {code, member_ids, reason}`);
    }
    if (!OBSERVATION_CODES.includes(o.code)) fail(`observations[${i}] has unknown code ${JSON.stringify(o.code)}`);
    if (!Array.isArray(o.member_ids) || o.member_ids.length === 0) fail(`observations[${i}] needs non-empty member_ids`);
    const mids = new Set();
    for (const id of o.member_ids) {
      if (typeof id !== "string" || !inputIds.includes(id)) fail(`observations[${i}] references unknown member ${JSON.stringify(id)}`);
      if (mids.has(id)) fail(`observations[${i}] repeats member ${JSON.stringify(id)}`);
      mids.add(id);
    }
    if (typeof o.reason !== "string" || o.reason.length === 0) fail(`observations[${i}] needs a non-empty reason`);
    if (o.reason.length > MAX_TEXT_ITEM_CHARS) fail(`observations[${i}].reason exceeds ${MAX_TEXT_ITEM_CHARS} chars`);
    return { code: o.code, member_ids: [...o.member_ids], reason: o.reason };
  });
  const questions = checkTextList(raw.questions, "questions", MAX_QUESTIONS);
  let unmodeled = checkTextList(raw.unmodeled, "unmodeled", MAX_UNMODELED);
  const review = "review" in raw ? checkTextList(raw.review, "review", MAX_REVIEW) : [];
  if (input.legacy_nearest_school && !unmodeled.some((t) => t.includes("POI prox"))) {
    if (unmodeled.length >= MAX_UNMODELED) fail("unmodeled is full; legacy school proxy notice has nowhere to go");
    unmodeled = [...unmodeled, LEGACY_SCHOOL_PROXY_NOTICE];
  }
  return {
    members, observations, questions, unmodeled, review,
    input_signature: input.input_signature,
    source: "muse",
    confirmed: false,
    days: input.days,
  };
}

// Restored transcripts or API payloads may carry forged minutes, costs,
// out-of-range frequencies, or extra keys under confirmed:true. Confirm and
// apply re-validate only the schema fields against this input, then match
// the signature and confirmation state — never trust the stored copy.
function renormalizePlan(plan, input) {
  if (!isObj(plan) || typeof plan.input_signature !== "string") fail("plan must carry input_signature");
  if (!isObj(input) || typeof input.input_signature !== "string") fail("input must carry input_signature");
  const raw = {
    members: plan.members,
    observations: plan.observations,
    questions: plan.questions,
    unmodeled: plan.unmodeled,
  };
  if (plan.review !== undefined) raw.review = plan.review;
  const clean = validateLifePlan(raw, input);
  if (clean.input_signature !== plan.input_signature || plan.input_signature !== input.input_signature) {
    fail("stale plan: profile, homes, dates, criteria, seed, or household changed since this plan was made");
  }
  return clean;
}

// A plan starts only on a fresh signature with every question resolved.
// The user answers questions by revising their text and generating a new
// plan; confirmation never fills gaps on its own.
export function confirmLifePlan(plan, input) {
  const clean = renormalizePlan(plan, input);
  if (Array.isArray(clean.questions) && clean.questions.length > 0) {
    fail("unresolved questions block starting; revise your text and generate a new plan");
  }
  // A member whose work never resolved must be explicitly cleared by this
  // plan (commute none or a valid known ref) — never silently executed as
  // a zero-minute commuter. Unknown work is clarified or proposed, and a
  // plan that leaves it untouched cannot confirm.
  for (const m of input.members || []) {
    if (m && m.work_unresolved === true) {
      const entry = clean.members.find((e) => e.id === m.id);
      const cleared = entry && entry.changes.some((c) => c.field === "commute");
      if (!cleared) fail(`member ${m.id} has unresolved work: clarify it or clear it with a commute change`);
    }
  }
  return { ...clean, confirmed: true };
}

export function applyLifePlan(scenario, plan, input) {
  if (!isObj(plan)) fail("plan must be an object");
  if (plan.confirmed !== true) fail("plan must be confirmed before applying (no confirmation, no apply)");
  const clean = renormalizePlan(plan, input);
  if (!isObj(scenario)) fail("scenario must be an object");
  const next = clone(scenario);
  const members = scenarioMembers(next);
  const byId = new Map(members.map((m) => [m.id, m]));
  // Snapshot ORIGINAL source work before any patch, so member:<id> copies
  // the engine-resolved work — never another patch.
  const sourceWork = new Map(members.map((m) => [m.id, clone(m.work)]));
  for (const entry of clean.members || []) {
    const target = byId.get(entry.id);
    if (!target) fail(`plan member ${JSON.stringify(entry.id)} is not in the scenario`);
    for (const c of entry.changes || []) {
      if (!CHANGE_FIELDS.includes(c.field)) fail(`unsupported field ${JSON.stringify(c.field)}`);
      if (c.field === "commute") {
        if (c.value === "none") {
          target.commute = "none";
          target.work = { type: "none" };
          target.work_unresolved = false;
        } else {
          const ref = /^member:(.+)$/.exec(c.value);
          target.work = clone(sourceWork.get(ref[1]));
          delete target.commute;
          target.work_unresolved = false;
        }
      } else {
        target[c.field] = clone(c.value);
      }
    }
  }
  // A plan that newly enables the legacy boolean school keeps old behavior
  // but records the proxy warning, like inputs that already had it.
  let unmodeled = clone(clean.unmodeled || []);
  const setsLegacySchool = clean.members.some((e) => e.changes.some((c) => c.field === "school" && c.value === true));
  if (setsLegacySchool && !unmodeled.some((t) => t.includes("POI prox"))) {
    if (unmodeled.length >= MAX_UNMODELED) fail("unmodeled is full; legacy school proxy notice has nowhere to go");
    unmodeled = [...unmodeled, LEGACY_SCHOOL_PROXY_NOTICE];
  }
  // Bounded per-member observation context for daily decision prompts,
  // plus the scenario-level join. Defaults stay visible assumptions here,
  // never relabelled as measured after confirmation.
  const bits = [];
  for (const entry of clean.members || []) {
    const rel = (clean.observations || []).filter((o) => o.member_ids.includes(entry.id));
    if (rel.length === 0) continue;
    const text = rel.map((o) => `[${o.code}] ${o.reason}`).join(" | ");
    const target = byId.get(entry.id);
    if (target) {
      target.plan_context = text.length > MAX_PLAN_CONTEXT_CHARS
        ? text.slice(0, MAX_PLAN_CONTEXT_CHARS) : text;
    }
    bits.push(`${entry.id}: ${text}`);
  }
  let plan_context = bits.join(" / ");
  if (plan_context.length > MAX_PLAN_CONTEXT_CHARS) plan_context = plan_context.slice(0, MAX_PLAN_CONTEXT_CHARS);
  next.plan_context = plan_context;
  next.life_plan = {
    source: "muse",
    confirmed: true,
    signature: clean.input_signature,
    days: typeof clean.days === "number" ? clean.days : input.days,
    applied_members: (clean.members || []).map((m) => m.id),
    observation_codes: [...new Set((clean.observations || []).map((o) => o.code))],
    unmodeled,
  };
  return next;
}

// Civil-date weekday math (pure integer arithmetic, no Date): 2026-11-02
// (a Monday) anchors the week, mirroring engine/scenario.js.
function daysFromCivil(y, m, d) {
  const yy = m <= 2 ? y - 1 : y;
  const era = Math.floor((yy >= 0 ? yy : yy - 399) / 400);
  const yoe = yy - era * 400;
  const mp = m <= 2 ? m + 9 : m - 3;
  const doy = Math.floor((153 * mp + 2) / 5) + d - 1;
  const doe = yoe * 365 + Math.floor(yoe / 4) - Math.floor(yoe / 100) + doy;
  return era * 146097 + doe - 719468;
}

const ANCHOR_DAYS = daysFromCivil(2026, 11, 2); // Monday

const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;

function weekdayIndexOfISO(text) {
  const m = DATE_RE.exec(text || "");
  if (!m) return null;
  const idx = (daysFromCivil(Number(m[1]), Number(m[2]), Number(m[3])) - ANCHOR_DAYS) % 7;
  return (idx + 7) % 7; // 0 = Mon
}

// Count how many times each weekday code occurs in [start, start+days).
export function countWeekdays(start_date, days) {
  const counts = { Mon: 0, Tue: 0, Wed: 0, Thu: 0, Fri: 0, Sat: 0, Sun: 0 };
  const start = weekdayIndexOfISO(start_date);
  if (start === null || !Number.isInteger(days) || days <= 0) return counts;
  for (let i = 0; i < days; i++) counts[WEEKDAYS[(start + i) % 7]] += 1;
  return counts;
}

function countCodes(counts, codes) {
  let n = 0;
  for (const c of codes || []) n += counts[c] || 0;
  return n;
}

function noTravelWork(member) {
  if (!isObj(member)) return false;
  // No trip legs exist for members with no work or work that never
  // resolved — counts are not completed routes. An explicit
  // home_office_days array wins over the legacy home_office flag
  // (including []), so it never triggers a blanket no-travel return.
  if (member.work_unresolved === true) return true;
  if (Array.isArray(member.home_office_days)) {
    if (member.commute === "none") return true;
    if (isObj(member.work) && member.work.type === "none") return true;
    return false;
  }
  if (member.home_office === true) return true;
  if (member.commute === "none") return true;
  if (isObj(member.work) && member.work.type === "none") return true;
  return false;
}

function countRemoteDays(member, counts) {
  const wds = Array.isArray(member && member.workdays) ? member.workdays : [];
  let n = 0;
  for (const w of wds) {
    if (isHomeOfficeDay(member, w)) n += counts[w] || 0;
  }
  return n;
}

