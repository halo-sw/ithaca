// Muse household life-plan provider call (no tools, JSON in/out).
//
// writeLifePlan sends one completeWithTools-compatible call shaped like
// consult/report.js: call({ provider, timeoutMs, maxTokens, messages }).
// The response is read from res.message.content as plain or fenced JSON
// and validated with validateLifePlan. Any provider failure or invalid
// plan throws: it never silently falls back to a canned plan labelled
// Muse.

import { validateLifePlan } from "../life/plan.js";

export const LIFE_PLAN_MAX_TOKENS = { default: 6000, baseten: 12000 };
export const LIFE_PLAN_TIMEOUT_MS = { default: 60000, baseten: 180000 };

export const LIFE_PLAN_PROMPT = `You compose a household routine plan from the household's stated needs. You do NOT select a persona template: one scenario may mix shift work, remote work, school-age children, seniors, and pets, and every member must be served without forcing them into one persona.

Read the JSON user input: members (id, label, role, work, workdays, home_office_days, schooldays, school, assumptions), user-sourced profile values, user message quotes (user_texts), homes, start_date, days, and input_signature. Scenario routine values are ASSUMPTIONS, not stated facts. Never describe them as what the household said. Existing scenario values may carry stereotypes (seniors, remote workers, pet defaults); never present those as facts. workdays lists ALL working days (onsite plus remote); home_office_days lists the remote subset of workdays.

Output ONLY one JSON object with EXACTLY these keys (an optional "review" array of at most 8 strings, each <=300 chars, is also allowed):
{"members":[{"id":string,"changes":[{"field":string,"value":any,"basis":"stated"|"proposal","evidence":string}]}],"observations":[{"code":string,"member_ids":[string],"reason":string}],"questions":[string],"unmodeled":[string]}

Bounds (violations are rejected, never repaired silently):
- Cover every input member exactly once: no duplicates, no invented ids, no omissions. A household member mismatch is a question, never a silent omission.
- At most 15 changes per member, 8 observations, 8 questions, 8 unmodeled strings (each <=300 chars).
- Whitelisted change fields ONLY: preferences (string <=500 chars); workdays/schooldays (non-empty arrays of unique weekday codes Mon..Sun; explicit no-commute uses the commute field); home_office_days (array, possibly empty, of unique weekday codes Mon..Sun; must be a subset of that member's effective workdays; explicit [] clears any legacy home_office true); errands_per_week (exactly {"supermarket":0..7,"convenience":0..7}); park_walks_per_week 0..7; clinic_visits_per_month 0..31; cafe_visits_per_week 0..5; vet_visits_per_month 0..4; home_office/dog_walk_morning (boolean; home_office true is legacy full-remote and stays valid, but an explicit home_office_days array overrides it, including []); commute ("none", or "member:<id>" copying that member's ORIGINAL resolved non-none work from the input — never another patch, routes, minutes, or costs); school (false, legacy true, or {mode:"unresolved"|"nearby", level:"elementary"|"middle"|"high"|"unknown"}; nearby needs a known level and is an optional route proposal, never an assignment). For hybrid days (for example onsite Mon/Wed/Fri with remote Tue/Thu) output workdays ["Mon","Tue","Wed","Thu","Fri"] plus home_office_days ["Tue","Thu"], not a blanket home_office boolean.
- basis "stated" requires evidence that is an exact substring of a USER message quote, or (any field except preferences) the exact user-sourced profile value for that same member and field. preferences evidence must always be user text, never demographic inference. Quoting is traceability, not proof: every stated extraction is reviewed by the user before anything executes.
- basis "proposal" stays visibly a proposal: optional routines are possible but clearly marked proposal and reviewable.
- Observation codes ONLY: commute, school, errands, walks, remote_days, clinic, pet_care, monthly_cost, daily_variation. member_ids must reference real input ids. Each reason is brief and specific to the stated routine.
- Never invent: no medical appointments for seniors, no cafes for remote workers, no vet appointments for pet owners, no shared workplace for every adult, no diagnoses or private health details — none without explicit basis.
- Missing workplace, school, or individual schedules are questions when the plan needs them; a child's grade or age alone never establishes school assignment. Do not demand irrelevant information: remote-only people do not need a workplace.
- Unknown or unsupported constraints (night shifts, accompaniment, accessibility, childcare coordination, actual catchment assignment, noise, daylight) go to unmodeled or a concrete question — never invented support.
- Respect stated workday and preference differences across household members.
- Rationale beyond brief specific observation reasons is generated by code from observations and the calendar; you only select the applicable observations.
- Never include totals, destinations, or any other top-level keys.`;

export function lifePlanPrompt(lang = "en") {
  const note = lang === "ko"
    ? "\nWrite user-facing strings (preferences, reasons, questions, unmodeled, review) in Korean."
    : "\nWrite user-facing strings (preferences, reasons, questions, unmodeled, review) in English.";
  return `${LIFE_PLAN_PROMPT}${note}`;
}

function stripFences(text) {
  const lines = String(text || "").split("\n");
  if (lines.length > 0 && lines[0].trim().startsWith("```")) lines.shift();
  const end = lines.lastIndexOf("```");
  if (end >= 0) lines.length = end;
  return lines.join("\n").trim();
}

export function parseLifePlanJSON(text) {
  const clean = stripFences(String(text || "").trim());
  if (!clean) throw new Error("life-plan: empty model response");
  return JSON.parse(clean);
}

// One model call, no tools. Returns { plan, usage }; the usage carries
// call provenance (provider/model) when the call returns them.
export async function writeLifePlan({ call, provider, input, lang = "en" } = {}) {
  if (typeof call !== "function") throw new Error("life-plan: call must be a function");
  if (!input || typeof input.input_signature !== "string") throw new Error("life-plan: input must carry input_signature");
  const maxTokens = provider === "baseten" ? LIFE_PLAN_MAX_TOKENS.baseten : LIFE_PLAN_MAX_TOKENS.default;
  const timeoutMs = provider === "baseten" ? LIFE_PLAN_TIMEOUT_MS.baseten : LIFE_PLAN_TIMEOUT_MS.default;
  const messages = [
    { role: "system", content: lifePlanPrompt(lang) },
    { role: "user", content: JSON.stringify(input) },
  ];
  let res;
  try {
    res = await call({ provider, timeoutMs, maxTokens, messages });
  } catch (err) {
    throw new Error(`life-plan: provider call failed: ${(err && err.message) || err}`);
  }
  const content = res && res.message && res.message.content;
  let raw;
  try {
    raw = parseLifePlanJSON(content);
  } catch (err) {
    throw new Error(`life-plan: invalid model JSON: ${(err && err.message) || err}`);
  }
  const plan = validateLifePlan(raw, input);
  const usage = { ...(res && res.usage ? res.usage : {}) };
  usage.provider = (res && res.provider) || provider;
  if (res && res.model) usage.model = res.model;
  return { plan, usage };
}
